import { mkdtemp, mkdir, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { deflateSync } from "node:zlib";
import { discoverBackends } from "../../src/backends.ts";
import { getPackageDir } from "@earendil-works/pi-coding-agent";

const root = fileURLToPath(new URL("../../", import.meta.url));
export const backends = discoverBackends();
export const pwsh = backends.find((value) => value.id === "pwsh7");
export async function createMxcFixture() {
  await mkdir(join(root, "docs", ".temp", "mxc-fixtures"), { recursive: true });
  const dir = await mkdtemp(join(root, "docs", ".temp", "mxc-fixtures", "run-"));
  const workspace = join(dir, "workspace");
  const reference = join(dir, "reference");
  const outside = join(dir, "outside");
  for (const path of [workspace, reference, outside]) await mkdir(path, { recursive: true });
  await writeFile(join(reference, "visible.txt"), "READ_ONLY_CANARY\n");
  await writeFile(join(reference, "denied.txt"), "DENIED_CANARY\n");
  await writeFile(join(outside, "sentinel.txt"), "OUTSIDE_CANARY\n");
  return {
    dir, workspace, reference, outside,
    options: {
      candidate: pwsh!, workspace, piPackageRoot: getPackageDir(),
      readonlyPaths: [reference], deniedPaths: [join(reference, "denied.txt")],
      scratchRoot: join(dir, "runner"),
    },
    cleanup: () => rm(dir, { recursive: true, force: true }),
  };
}

// An independent, minimal 2x1 RGBA PNG fixture, not generated by Pi's decoder.
export function smallPng(): Buffer {
  function crc32(bytes: Buffer): number {
    let crc = 0xffffffff;
    for (const byte of bytes) {
      crc ^= byte;
      for (let i = 0; i < 8; i++) crc = (crc >>> 1) ^ (crc & 1 ? 0xedb88320 : 0);
    }
    return (crc ^ 0xffffffff) >>> 0;
  }
  function chunk(name: string, body: Buffer): Buffer {
    const bytes = Buffer.concat([Buffer.from(name), body]);
    const result = Buffer.alloc(12 + body.length);
    result.writeUInt32BE(body.length, 0);
    bytes.copy(result, 4);
    result.writeUInt32BE(crc32(bytes), result.length - 4);
    return result;
  }
  const header = Buffer.alloc(13);
  header.writeUInt32BE(2, 0); header.writeUInt32BE(1, 4);
  header[8] = 8; header[9] = 6;
  return Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk("IHDR", header),
    chunk("IDAT", deflateSync(Buffer.from([0, 255, 0, 0, 255, 0, 0, 255, 255]))),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}
